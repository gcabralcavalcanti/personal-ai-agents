"""Shared page shell for the demo outputs: one look for every agent's page, light and dark."""

from __future__ import annotations

import html
from pathlib import Path

AGENTS = [
    (
        "secretary",
        "Secretary",
        "Plans the day in the task manager; a gate blocks any write the validator did not pass.",
    ),
    ("habits", "Habits", "Turns the habit-tracker export into a spreadsheet and a dashboard of habits."),
    ("goals", "Goals", "Shows the quarter's goals and key results against what the data says."),
    ("career", "Career", "Reads public job boards and sorts new openings into apply, monitor or discard."),
]

LIBRARIAN_URL = "https://github.com/gcabralcavalcanti/anki-librarian-mcp"
CSS = (Path(__file__).with_name("pages.css")).read_text(encoding="utf-8")


def esc(text) -> str:
    return html.escape(str(text if text is not None else ""))


def shell(page: str, title: str, lead: str, body: str, extra_css: str = "", data_note: str = "Fictitious data.") -> str:
    links = ['<a href="index.html"' + (' class="on"' if page == "index" else "") + ">All agents</a>"]
    links += [f'<a href="{k}.html"' + (' class="on"' if page == k else "") + f">{n}</a>" for k, n, _ in AGENTS]
    return f"""<!doctype html><html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1"><title>{esc(title)}</title>
<style>{CSS}{extra_css}</style></head><body><main><nav>{"".join(links)}</nav>
<h1>{esc(title)}</h1><p class="lead">{lead}</p>{body}
<footer>{esc(data_note)} Generated by <code>python demo.py</code> in personal-ai-agents.</footer>
</main></body></html>"""


def index(status: dict[str, str]) -> str:
    cards = "".join(
        f'<a class="panel" href="{k}.html" style="color:inherit;text-decoration:none"><h2 style="margin:0 0 6px">'
        f"{esc(n)}</h2><p class='muted' style='margin:0'>{esc(d)}</p>"
        f"<p style='margin:8px 0 0'>{status.get(k, '')}</p></a>"
        for k, n, d in AGENTS
    )
    cards += (
        f'<a class="panel" href="{LIBRARIAN_URL}" style="color:inherit;text-decoration:none">'
        '<h2 style="margin:0 0 6px">Librarian (flashcards)</h2><p class="muted" style="margin:0">Turns study '
        "material into Anki flashcards with the same safety rules.</p><p style='margin:8px 0 0'>Lives in its own "
        "repository, anki-librarian-mcp, with a step-by-step simulation.</p></a>"
    )
    lead = (
        "Each agent here is a small, runnable version of one I use every day with my real data (Todoist, Anki, Loop "
        "Habits, Claude Code). The data on these pages is fictitious; the logic and the outputs are the real ones."
    )
    note = "Fictitious data, except the public job boards on the Career page."
    return shell("index", "Personal AI agents", lead, f'<div class="grid g2">{cards}</div>', data_note=note)
